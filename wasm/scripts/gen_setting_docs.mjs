#!/usr/bin/env node
/**
 * Regenerates app/src/settings/settingDocsMap.ts: the documentation page of each option, as desktop passes it to
 * append_single_option_line("<option>", "<wiki path>[#anchor]") in src/slic3r/GUI/Tab.cpp.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = fs.readFileSync(path.join(here, '../../src/slic3r/GUI/Tab.cpp'), 'utf8');
const map = {};
for (const m of source.matchAll(/append_single_option_line\(\s*"([a-z0-9_]+)"\s*,\s*"([a-z0-9_#-]+)"/g)) map[m[1]] ??= m[2];
const body = Object.keys(map).sort().map((k) => `  ${k}: '${map[k]}',`).join('\n');
fs.writeFileSync(path.join(here, '../app/src/settings/settingDocsMap.ts'),
  `// Generated by wasm/scripts/gen_setting_docs.mjs from src/slic3r/GUI/Tab.cpp; do not edit.\nexport const SETTING_DOC_PATHS: Record<string, string> = {\n${body}\n};\n`);
console.log(`${Object.keys(map).length} options`);
