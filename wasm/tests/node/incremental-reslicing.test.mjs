function normalizeGcode(bytes) {
  const text = typeof bytes === 'string' ? bytes : Buffer.from(bytes).toString('utf8');
  return text.replace(/^; generated by .*$/gm, '');
}

function compareWithScript(actualBytes, expectedBytes, tag) {
  const actualPath = path.join(scratchDir, `${tag}_actual.gcode`);
  const expectedPath = path.join(scratchDir, `${tag}_expected.gcode`);
  fs.writeFileSync(actualPath, actualBytes);
  fs.writeFileSync(expectedPath, expectedBytes);
  execFileSync('bash', [compareScript, expectedPath, actualPath], { stdio: 'pipe' });
}

function assertSliceEquivalent(actualRes, refEntry, label, { runCompareScript = false, tag = '' } = {}) {
  const refRes = refEntry.res || refEntry;
  const refGcode = refEntry.gcode !== undefined && typeof refEntry.gcode === 'string'
    ? refEntry.gcode
    : normalizeGcode(refRes.gcode);
  const refRawBytes = refEntry.rawBytes || refRes.gcode;
  const actualGcode = normalizeGcode(actualRes.gcode);
  if (actualGcode !== refGcode) {
    const aLines = actualGcode.split('\n');
    const bLines = refGcode.split('\n');
    const diffs = [];
    for (let i = 0; i < Math.max(aLines.length, bLines.length) && diffs.length < 10; i++) {
      if (aLines[i] !== bLines[i]) {
        diffs.push(`line ${i + 1}: actual=${JSON.stringify(aLines[i])} expected=${JSON.stringify(bLines[i])}`);
      }
    }
    assert.fail(`${label}: normalized G-code mismatch (lines ${aLines.length} vs ${bLines.length}, time ${actualRes.printTimeS} vs ${refRes.printTimeS})\n${diffs.join('\n')}`);
  }
  assert.equal(actualRes.layers, refRes.layers, `${label}: layers mismatch`);
  assert.equal(actualRes.filamentMm, refRes.filamentMm, `${label}: filamentMm mismatch`);
  assert.equal(actualRes.filamentG, refRes.filamentG, `${label}: filamentG mismatch`);
  assert.equal(actualRes.printTimeS, refRes.printTimeS, `${label}: printTimeS mismatch`);
  assert.deepEqual(actualRes.warnings, refRes.warnings, `${label}: warnings mismatch`);
  if (runCompareScript) {
    compareWithScript(actualRes.gcode, refRawBytes, tag || label.replace(/[^a-zA-Z0-9_-]/g, '_'));
  }
}

async function initEngine(moduleFactory) {
  const core = await createEngineCore({ moduleFactory, threads: THREADS });
  for (const file of ['resources.json', 'profiles/OrcaFilamentLibrary.json', 'profiles/Voron.json']) {
    await core.addVendorBundle(JSON.parse(fs.readFileSync(path.join(bundleDir, file), 'utf8')));
  }
  await core.call('init', { resourcesDir: '/resources', dataDir: '/data' });
  await core.call('loadVendors', {});
  await core.call('selectPresets', PRESETS);
  return core;
}

