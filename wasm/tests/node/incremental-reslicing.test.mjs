  async function sliceFreshReference(setupFn, sliceOpts = {}) {
    await refCore.call('resetOptions', {});
    await refCore.call('selectPresets', PRESETS);
    let plates = await refCore.call('listPlates', {});
    while (plates.length > 1) {
      plates = await refCore.call('deletePlate', { plateIndex: plates.length - 1, deleteObjects: true });
    }
    const model = await refCore.loadModel('20mm_cube.obj', cubeBytes);
    await refCore.call('arrange', {});
    if (setupFn) {
      await setupFn(refCore, model);
    }
    const res = await refCore.slice({ outPath: '/out/ref.gcode', threads: THREADS, ...sliceOpts });
    return {
      res,
      gcode: normalizeGcode(res.gcode),
      rawBytes: res.gcode
    };
  }

