import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { createEngineCore } from '../../web/engine-core.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const modulePath = path.resolve(process.env.ORCA_ENGINE_MODULE || 'wasm/build/multipart-volume-api-runtime/wasm/engine/orca_engine.mjs');
const hash = value => createHash('sha256').update(value).digest('hex');
const near = (actual, expected, tolerance = 1e-9) => actual.forEach((v, i) => assert.ok(Math.abs(v - expected[i]) < tolerance, `${actual} != ${expected}`));

async function engine() {
  const mod = await import(modulePath);
  const core = await createEngineCore({ moduleFactory: mod.createOrcaEngine || mod.default, threads: 2 });
  for (const file of ['resources.json', 'profiles/OrcaFilamentLibrary.json', 'profiles/Voron.json'])
    await core.addVendorBundle(JSON.parse(fs.readFileSync(path.join(root, 'wasm/build/tests-node', file), 'utf8')));
  await core.call('init', { resourcesDir: '/resources', dataDir: '/data' });
  await core.call('loadVendors', {});
  await core.call('selectPresets', { printer: 'Voron 2.4 300 0.4 nozzle', process: '0.20mm Standard @Voron', filaments: ['Generic PLA @System'] });
  await core.loadModel('20mm_cube.obj', fs.readFileSync(path.join(root, 'tests/data/20mm_cube.obj')));
  return core;
}

test('default cube matches pre-extension active commands, config, statistics and mesh', async () => {
  const core = await engine();
  try {
    await core.call('arrange', {});
    const [obj] = await core.call('listObjects', {});
    const mesh = await core.call('getMesh', { objectId: obj.id });
    const meshHash = hash(core.readFile(mesh.path));
    const config = await core.call('getConfig', {});
    const stats = await core.call('slice', { outPath: '/out/cube.gcode', threads: 2 });
    assert.equal(stats.layers, 100);
    const gcode = new TextDecoder().decode(core.readFile('/out/cube.gcode'));
    const canonical = gcode.replace(/^; generated by .*$/m, '').replace(/^(; (?:stop )?printing object .* id:)\d+(?= copy \d+$)/gm, '$1<ID>');
    const gate = { meshHash, configHash: hash(JSON.stringify(config)), stats, canonicalHash: hash(canonical), commandHash: hash(gcode.split('\n').filter(line => line.trim() && !line.trim().startsWith(';')).join('\n')) };
    console.log('CUBE_GATE ' + JSON.stringify(gate));
    if (process.env.MULTIPART_CUBE_BASELINE)
      assert.deepEqual(gate, JSON.parse(fs.readFileSync(process.env.MULTIPART_CUBE_BASELINE, 'utf8')));
  } finally { core.dispose(); }
});

test('native volume transforms, all viewer partitions, shared instances and history snapshots', { skip: !!process.env.MULTIPART_BASELINE_ONLY }, async () => {
  const core = await engine();
  const call = (op, args = {}) => core.call(op, args);
  try {
    const { objects: [obj] } = await call('getObjectTree');
    const objectId = obj.id;
    const originalId = obj.volumes[0].id;
    const ref = volumeId => ({ objectId, volumeId });
    const original = await call('getVolume', ref(originalId));
    near(original.rotation, [0, 0, 0]); near(original.scale, [1, 1, 1]); near(original.mirror, [1, 1, 1]);
    const part = await call('addVolume', { objectId, type: 'part', shape: 'cube', size: 12, offset: [35, 0, 0], name: 'editable' });
    const defaultBefore = await call('getMesh', { objectId });
    const defaultBytes = new Uint8Array(core.readFile(defaultBefore.path));
    const added = [];
    for (const type of ['negative', 'modifier', 'support_blocker', 'support_enforcer'])
      added.push(await call('addVolume', { objectId, type, shape: 'cube', size: 8, offset: [0, 35, 0], name: type }));
    const defaultAfter = await call('getMesh', { objectId });
    assert.deepEqual(defaultAfter, defaultBefore);
    assert.deepEqual(core.readFile(defaultAfter.path), defaultBytes);
    const viewer = await call('getMesh', { objectId, forViewer: true });
    assert.equal(viewer.volumes.length, 6);
    const bytes = core.readFile(viewer.path);
    const data = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
    assert.equal(data.getUint32(0, true), 0x4d455348);
    for (const meta of viewer.volumes) {
      assert.ok(meta.facetCount > 0 && meta.vertexCount > 0);
      assert.deepEqual(await call('getVolume', ref(meta.volumeId)), Object.fromEntries(Object.entries(meta).filter(([key]) => !['firstFacet', 'facetCount', 'firstVertex', 'vertexCount'].includes(key))));
      const min = [Infinity, Infinity, Infinity], max = [-Infinity, -Infinity, -Infinity];
      for (let i = meta.firstVertex; i < meta.firstVertex + meta.vertexCount; ++i)
        for (let axis = 0; axis < 3; ++axis) {
          const value = data.getFloat32(16 + (3 * i + axis) * 4, true);
          min[axis] = Math.min(min[axis], value); max[axis] = Math.max(max[axis], value);
        }
      near(min, meta.localBounds.min); near(max, meta.localBounds.max);
    }
    assert.deepEqual(viewer.volumes.map(v => v.type), ['part', 'part', 'negative', 'modifier', 'support_blocker', 'support_enforcer']);
    const [before] = await call('listObjects');
    await call('duplicateInstance', { objectId, instanceId: before.instances[0].id });
    const parents = (await call('listObjects'))[0].instances;
    const siblings = await Promise.all([originalId, ...added.map(v => v.volumeId)].map(v => call('getVolume', ref(v))));
    await call('saveProject', { path: '/out/undo_slot_0.3mf', compressionLevel: 2 });
    await call('setVolumeTransform', { ...ref(part.volumeId), scale: [2, 3, 4], mirror: [-1, 1, 1] });
    await call('setVolumeTransform', { ...ref(part.volumeId), offset: [40, 2, 3] });
    const changed = await call('setVolumeTransform', { ...ref(part.volumeId), rotation: [0, 0, Math.PI / 6] });
    near(changed.offset, [40, 2, 3]); near(changed.rotation, [0, 0, Math.PI / 6]);
    near(changed.scale, [2, 3, 4]); near(changed.mirror, [-1, 1, 1]);
    assert.deepEqual((await call('listObjects'))[0].instances, parents);
    assert.deepEqual(await Promise.all([originalId, ...added.map(v => v.volumeId)].map(v => call('getVolume', ref(v)))), siblings);
    for (const args of [{ objectId: 0, volumeId: part.volumeId }, { objectId, volumeId: 0 }, { objectId: 999999, volumeId: part.volumeId }, { objectId, volumeId: 999999 }]) {
      await assert.rejects(call('getVolume', args), /not found/i);
      await assert.rejects(call('setVolumeTransform', { ...args, offset: [0, 0, 0] }), /not found/i);
    }
    await assert.rejects(call('getVolume', { objectId, volumeId: part.volumeId + 0.1 }), /Invalid volumeId/);
    for (const bad of [NaN, Infinity, -Infinity, null])
      await assert.rejects(call('setVolumeTransform', { ...ref(part.volumeId), offset: [99, 0, 0], rotation: [0, bad, 0] }));
    await assert.rejects(call('setVolumeTransform', { ...ref(part.volumeId), scale: 0 }));
    assert.deepEqual(await call('getVolume', ref(part.volumeId)), changed);
    await call('saveProject', { path: '/out/undo_slot_1.3mf', compressionLevel: 2 });
    const readEdited = async () => {
      const { objects: [restored] } = await call('getObjectTree');
      return call('getVolume', { objectId: restored.id, volumeId: restored.volumes.find(v => v.name === 'editable').id });
    };
    // The application's undo/redo restores these native project snapshots.
    await call('openProject', { path: '/out/undo_slot_0.3mf' });
    const undone = await readEdited();
    near(undone.offset, [35, 0, 0]); near(undone.rotation, [0, 0, 0]); near(undone.scale, [1, 1, 1]);
    await call('openProject', { path: '/out/undo_slot_1.3mf' });
    const redone = await readEdited();
    // Native 3MF matrix serialization rounds its decimal representation.
    for (const key of ['offset', 'rotation', 'scale', 'mirror']) near(redone[key], changed[key], 1e-6);
    assert.equal((await call('listObjects'))[0].instances.length, 2);
    const reset = await call('setVolumeTransform', { objectId: redone.objectId, volumeId: redone.volumeId, offset: [0, 0, 0], rotation: [0, 0, 0], scale: 1, mirror: [1, 1, 1] });
    near(reset.offset, [0, 0, 0]); near(reset.rotation, [0, 0, 0]); near(reset.scale, [1, 1, 1]); near(reset.mirror, [1, 1, 1]);
  } finally { core.dispose(); }
});
