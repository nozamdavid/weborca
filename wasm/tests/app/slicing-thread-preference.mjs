#!/usr/bin/env node
/** Frozen-artifact Chromium regression, following prefs.mjs and the app harness. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
import { chromium } from '../node_modules/playwright/index.mjs';
import { startServer, stopServer } from './lib/dist.mjs';
import { selectAddedPrinter } from './lib/printer.mjs';

const port = Number(process.env.PORT || 5317);
const url = process.env.APP_TEST_BASE_URL || `http://127.0.0.1:${port}`;
const output = process.env.APP_TEST_OUTPUT;
assert.ok(output, 'APP_TEST_OUTPUT must name the private evidence directory');
assert.equal(process.env.APP_TEST_FROZEN_DIST, '1');
const evidence = { checks: [], worker: [], errors: [], blocked: [], layouts: [] };
const save = () => fs.writeFileSync(`${output}/results.json`, JSON.stringify(evidence, null, 2));
const pass = name => { evidence.checks.push(name); console.log(`PASS ${name}`); save(); };
const hash = text => crypto.createHash('sha256').update(text).digest('hex');
const normalized = text => text.replace(/^; generated by .*$/m, '').replace(/^(; (?:stop )?printing object .* id:)\d+(?= copy \d+$)/gm, '$1<ID>');
const browser = await chromium.launch({ args: ['--enable-features=SharedArrayBuffer', '--enable-unsafe-swiftshader'] });
let page;
async function fresh(hardware, preference, failInit = false) {
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, acceptDownloads: true, serviceWorkers: 'block' });
  await context.route('**/*', async route => {
    const request = route.request(), target = new URL(request.url());
    if (target.origin !== url || /^\/(?:_printer|_cloud|api|orca-cloud)\//.test(target.pathname)) {
      evidence.blocked.push(request.url()); save(); await route.abort();
    } else await route.continue();
  });
  await context.addInitScript(({ hardware, preference, failInit }) => {
    Object.defineProperty(navigator, 'hardwareConcurrency', { get: () => hardware });
    localStorage.setItem('orca.wizard', JSON.stringify({ printers: ['Voron 2.4 300 0.4 nozzle'], filaments: [], completedAt: '2026-10-13' }));
    if (preference !== undefined && !sessionStorage.getItem('thread-test-seeded')) {
      localStorage.setItem('orcaslicer_preferences_v1', JSON.stringify({ general: { slicingThreads: preference, language: 'en' } }));
      sessionStorage.setItem('thread-test-seeded', '1');
    }
    window.__threadMessages = [];
    let count = 0, fail = failInit;
    const Worker = window.Worker;
    window.Worker = new Proxy(Worker, { construct(target, args) {
      const worker = Reflect.construct(target, args), id = ++count;
      const original = worker.postMessage;
      worker.postMessage = function (...parameters) {
        const message = parameters[0];
        if (['init', 'slice', 'abort'].includes(message?.method)) {
          const entry = { direction: 'request', worker: id, method: message.method, threads: message.args?.threads, plateIndex: message.args?.plateIndex, time: performance.now() };
          window.__threadMessages.push(entry); console.log('[thread-test] ' + JSON.stringify(entry));
          if (message.method === 'init' && fail) {
            fail = false;
            worker.terminate();
            setTimeout(() => worker.dispatchEvent(new ErrorEvent('error', { message: 'thread-test isolated init request failure' })), 100);
            return;
          }
        }
        return original.apply(this, parameters);
      };
      worker.addEventListener('message', event => {
        if (event.data?.progress && window.__changeThreadDuringJob) {
          window.__changeThreadDuringJob = false;
          window.__prefsStore.getState().setGeneralPref('slicingThreads', 16);
          window.__midJobChanged = true;
        }
      });
      return worker;
    } });
  }, { hardware, preference, failInit });
  page = await context.newPage();
  page.on('pageerror', error => { evidence.errors.push(error.stack || error.message); save(); });
  page.on('requestfailed', request => console.log('REQUEST FAILED', request.url(), request.failure()?.errorText));
  page.on('response', response => { if (response.status() >= 400) { evidence.errors.push(`HTTP ${response.status()} ${response.url()}`); save(); } });
  page.on('console', message => {
    if (message.text().startsWith('[thread-test] ')) { evidence.worker.push(JSON.parse(message.text().slice(14))); save(); }
    else if (message.type() === 'error') console.error('BROWSER', message.text());
  });
  await page.goto(url);
  assert.equal(await page.evaluate(() => crossOriginIsolated), true);
  if (!failInit) await ready();
  return context;
}
async function ready() {
  await page.waitForFunction(() => window.__appStore?.getState().isEngineReady || window.__appStore?.getState().engineError, null, { timeout: 90000 });
  assert.equal(await page.evaluate(() => window.__appStore.getState().engineError), null);
}
async function setupCube() {
  await page.evaluate(() => window.__wizardStore?.getState().close?.());
  // The maintained picker helper persists local preset names, never device hosts.
  await selectAddedPrinter(page, 'Voron');
  await page.evaluate(() => window.__prefsStore.getState().setGeneralPref('autosave', false));
  await page.selectOption('#process-select', '0.20mm Standard @Voron');
  await page.selectOption('#filament-select', 'Generic PLA @System');
  await page.setInputFiles('#model-file', 'tests/data/20mm_cube.obj');
  await page.waitForFunction(() => window.__appStore.getState().modelObjects?.length && !window.__appStore.getState().isModelLoading);
}
const messages = () => page.evaluate(() => window.__threadMessages);
async function slice(plate = false) {
  await page.evaluate(async plate => {
    if (plate) await window.__platesStore.getState().slicePlate(0);
    else await window.__appStore.getState().startSlice();
  }, plate);
  assert.equal(await page.evaluate(() => window.__appStore.getState().engineError), null);
  assert.ok(await page.evaluate(() => window.__appStore.getState().sliceResult?.gcode.length > 0));
}
async function result() {
  return page.evaluate(async () => {
    const state = window.__appStore.getState(), engine = window.__orcaEngine;
    return { config: await engine.getConfig(), gcode: await (await fetch(state.gcodeUrl)).text(), stats: { ...state.sliceResult, gcode: undefined } };
  });
}
async function preview() {
  await page.waitForFunction(() => document.querySelector('#preview-error-overlay') || (window.__previewStore?.getState().layersCount > 0 && document.querySelector('#canvas')?.dataset.previewReady === 'true'), null, { timeout: 180000 });
  assert.equal(await page.locator('#preview-error-overlay').count(), 0);
  const before = await page.evaluate(() => window.__previewStore.getState().maxLayer);
  await page.locator('#layer-slider-max').fill('1', { force: true });
  await page.locator('#layer-slider-max').dispatchEvent('input');
  const after = await page.evaluate(() => ({ range: window.__previewStore.getState().maxLayer, layers: window.__previewStore.getState().layersCount, engine: window.__appStore.getState().isEngineReady }));
  console.log('PREVIEW', JSON.stringify({ before, ...after }));
  assert.ok(after.layers > 0 && after.engine);
  assert.equal(after.range, 1);
  assert.ok(before > after.range);
}
try {
  if (!process.env.APP_TEST_BASE_URL) await startServer(port, 'thread-preference');
  let context = await fresh(32);
  await page.keyboard.press('Escape');
  await page.keyboard.press('Control+p');
  await page.waitForSelector('#pref-slicing-threads');
  assert.equal(await page.locator('#pref-slicing-threads').inputValue(), 'auto');
  assert.deepEqual(await page.locator('#pref-slicing-threads option').evaluateAll(options => options.map(o => o.value)), ['auto', '1', '2', '4', '8', '16']);
  for (const language of ['en', 'es']) for (const [width, height] of [[1280, 900], [390, 844]]) for (const fontScale of [100, 150]) {
    await page.setViewportSize({ width, height });
    await page.evaluate(({ language, fontScale }) => { window.__prefsStore.getState().setGeneralPref('language', language); window.__prefsStore.getState().setDisplayPref('fontScale', fontScale); }, { language, fontScale });
    await page.waitForTimeout(100);
    const layout = await page.evaluate(() => ['pref-slicing-threads', 'pref-slicing-threads-help', 'pref-close-btn'].map(id => {
      const element = document.getElementById(id), rect = element.getBoundingClientRect();
      return { id, text: element.textContent, visible: rect.left >= 0 && rect.right <= innerWidth && rect.top >= 0 && rect.bottom <= innerHeight, clipped: element.scrollWidth > element.clientWidth };
    }));
    evidence.layouts.push({ language, width, height, fontScale, layout }); save();
    assert.ok(layout.every(item => item.visible && !item.clipped), JSON.stringify(layout));
    await page.screenshot({ path: `${output}/chromium-${language}-${width}-${fontScale}.png` });
  }
  pass('six choices, Auto default, English/Spanish layout at both sizes and font scales');
  await page.selectOption('#pref-slicing-threads', '16');
  await page.reload(); await ready();
  assert.equal(await page.evaluate(() => window.__prefsStore.getState().general.slicingThreads), 16);
  await page.evaluate(() => window.__prefsStore.getState().resetDefaults());
  assert.equal(await page.evaluate(() => window.__prefsStore.getState().general.slicingThreads), 'auto');
  for (const general of [{ slicingThreads: 32, language: 'es', units: 'imperial' }, { language: 'es', units: 'imperial' }]) {
    await page.evaluate(general => localStorage.setItem('orcaslicer_preferences_v1', JSON.stringify({ general })), general);
    await page.reload(); await ready();
    assert.deepEqual(await page.evaluate(() => { const g = window.__prefsStore.getState().general; return [g.slicingThreads, g.language, g.units]; }), ['auto', 'es', 'imperial']);
  }
  pass('16 survives real reload; reset Auto; invalid and legacy reload preserve other preferences');
  await context.close();
  context = await fresh(32);
  await page.keyboard.press('Escape');
  await setupCube();
  assert.equal((await messages()).find(m => m.method === 'init').threads, 8);
  await slice(); const eight = await result();
  assert.equal((await messages()).filter(m => m.method === 'slice').at(-1).threads, 8);
  await page.evaluate(() => {
    const a = window.__appStore.getState(), p = window.__previewStore.getState();
    const before = [a.currentConfig, a.pendingOptions, a.sliceResult, a.gcodeUrl, p.stats, p.layersCount, window.__orcaEngine];
    window.__prefsStore.getState().setGeneralPref('slicingThreads', 16);
    const b = window.__appStore.getState(), q = window.__previewStore.getState();
    if (!before.every((value, i) => value === [b.currentConfig, b.pendingOptions, b.sliceResult, b.gcodeUrl, q.stats, q.layersCount, window.__orcaEngine][i])) throw new Error('Preference invalidated application state');
  });
  await slice(); const sixteen = await result();
  assert.deepEqual(sixteen.config, eight.config);
  assert.equal(hash(normalized(sixteen.gcode)), hash(normalized(eight.gcode)));
  let requests = await messages();
  assert.equal(requests.filter(m => m.method === 'slice').at(-1).threads, 16);
  assert.equal(requests.filter(m => m.method === 'init').length, 1);
  await slice(true);
  assert.equal((await messages()).filter(m => m.method === 'slice').at(-1).threads, 16);
  pass('hardware32 creation Auto8, ordinary Auto8/16 same real engine, plate16, exact config and narrow G-code parity, no preference invalidation');
  await page.evaluate(() => { window.__prefsStore.getState().setGeneralPref('slicingThreads', 'auto'); window.__changeThreadDuringJob = true; });
  await slice();
  assert.equal(await page.evaluate(() => window.__midJobChanged), true);
  assert.equal((await messages()).filter(m => m.method === 'slice').at(-1).threads, 8);
  assert.equal(await page.evaluate(() => window.__prefsStore.getState().general.slicingThreads), 16);
  await slice();
  assert.equal((await messages()).filter(m => m.method === 'slice').at(-1).threads, 16);
  pass('preference changed on real progress: submitted job8 completes, next job16');
  await page.evaluate(() => { window.__cancelPromise = window.__appStore.getState().startSlice(); });
  await page.waitForFunction(() => window.__threadMessages.filter(m => m.method === 'slice').length >= 6);
  await page.evaluate(() => window.__appStore.getState().cancelSlice());
  await page.evaluate(() => window.__cancelPromise);
  assert.ok((await messages()).some(m => m.method === 'abort'));
  assert.equal(await page.evaluate(() => window.__appStore.getState().isSlicing), false);
  assert.equal(await page.evaluate(() => window.__appStore.getState().sliceStatusText), 'Slicing canceled.');
  assert.equal(await page.evaluate(() => window.__appStore.getState().sliceResult), null);
  await slice(); await preview();
  pass('real worker abort followed by successful slice16 and preview coexistence');
  await context.close();
  context = await fresh(8, 16); await page.keyboard.press('Escape'); await setupCube();
  await slice(); await slice(true);
  requests = await messages();
  assert.deepEqual(requests.filter(m => ['init', 'slice'].includes(m.method)).map(m => m.threads), [8, 8, 8]);
  pass('hardware8 persisted16 clamps creation and both real job paths to8');
  await context.close();
  context = await fresh(32, 'auto', true);
  await page.waitForFunction(() => window.__appStore?.getState().engineError?.includes('isolated init request failure'));
  await page.evaluate(async () => { window.__prefsStore.getState().setGeneralPref('slicingThreads', 16); await window.__appStore.getState().initApp(); });
  await ready();
  assert.deepEqual((await messages()).filter(m => m.method === 'init').map(m => m.threads), [8, 16]);
  await page.keyboard.press('Escape'); await setupCube(); await slice();
  pass('isolated failed init request retries current preference16 and real engine slices');
  await context.close();
  if (process.env.APP_TEST_PRIVATE_PROJECT) {
    context = await fresh(32, 16); await page.keyboard.press('Escape');
    await page.evaluate(async () => { window.__prefsStore.getState().setGeneralPref('autosave', false); await window.__appStore.getState().chooseVendor('BBL'); });
    await page.setInputFiles('#project-file-input', process.env.APP_TEST_PRIVATE_PROJECT);
    await page.waitForFunction(() => window.__appStore.getState().engineError || (!window.__appStore.getState().isModelLoading && window.__appStore.getState().modelObjects?.length), null, { timeout: 180000 });
    assert.equal(await page.evaluate(() => window.__appStore.getState().engineError), null);
    await page.waitForFunction(() => window.__historyStore.getState().currentSnapshot?.modelFileName === window.__appStore.getState().modelFile.name, null, { timeout: 180000 });
    await page.click('#slice-btn');
    await page.waitForFunction(() => !window.__appStore.getState().isSlicing && (window.__appStore.getState().sliceResult || window.__appStore.getState().engineError), null, { timeout: 240000 });
    assert.equal(await page.evaluate(() => window.__appStore.getState().engineError), null);
    const actual = await result();
    evidence.privateProject = { configHash: hash(JSON.stringify(actual.config)), normalizedHash: hash(normalized(actual.gcode)), canonicalHash: hash(actual.gcode.split('\n').filter(line => line.trim() && !line.trimStart().startsWith(';')).join('\n')), stats: { ...actual.stats, gcode: undefined } };
    const readbackHash = await page.evaluate(async () => { const s = window.__appStore.getState(); const bytes = await window.__orcaEngine.readFile(s.sliceResult.gcodePath); return Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256', bytes))); });
    assert.equal(Buffer.from(readbackHash).toString('hex'), hash(actual.gcode));
    const referenceLog = fs.readFileSync('docs/superpowers/performance-20261013/resumed-sol/higher-thread-paired/resumed-accepted-1-slice.log', 'utf8');
    const reference = JSON.parse(referenceLog.split('\n').find(line => line.startsWith('{"module"')));
    evidence.privateProject.referenceConfigHash = reference.configHash;
    if (evidence.privateProject.configHash === reference.configHash) {
      assert.equal(evidence.privateProject.normalizedHash, reference.normalizedHash);
      assert.equal(evidence.privateProject.canonicalHash, reference.commandHash);
    } else evidence.privateProject.parityScope = 'UI project import configuration differs from the maintained engine fixture; normalization was not widened.';
    save();
    await preview();
    // Await both operations together so a listener timeout is retained by catch.
    const [download] = await Promise.all([
      page.waitForEvent('download'),
      page.click('#download-link')
    ]);
    await download.saveAs(`${output}/sylvanas-export.gcode`);
    const exported = fs.readFileSync(`${output}/sylvanas-export.gcode`, 'utf8');
    evidence.privateProject.exportBytes = Buffer.byteLength(exported);
    evidence.privateProject.exportSha256 = hash(exported);
    assert.equal(hash(exported.split('\n').filter(line => line.trim() && !line.trimStart().startsWith(';')).join('\n')), evidence.privateProject.canonicalHash);
    await page.keyboard.press('Control+p'); await page.waitForSelector('#pref-slicing-threads');
    await page.click('#pref-close-btn');
    await page.screenshot({ path: `${output}/sylvanas-preview.png` });
    pass('private local UI project import, slice16, export/readback, preview sliders and Preferences button response');
    await context.close();
  }
  assert.deepEqual(evidence.errors, []);
  assert.deepEqual(evidence.blocked, []);
} catch (error) {
  evidence.failure = error.stack; save(); console.error(error);
  if (page && !page.isClosed()) await page.screenshot({ path: `${output}/failure.png` }).catch(() => {});
  process.exitCode = 1;
} finally {
  await browser.close();
  if (!process.env.APP_TEST_BASE_URL) await stopServer(port);
  save();
}
