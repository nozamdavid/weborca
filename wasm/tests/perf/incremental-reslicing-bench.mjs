#!/usr/bin/env node
/**
 * Incremental reslicing benchmark: compares retained Slic3r::Print against a
 * fresh-Print baseline (separate baseline build or fresh loadModel) on 3DBenchy.stl,
 * verifies normalized G-code hash equivalence for every scenario, and checks
 * RSS / WASM heap growth across 10 consecutive incremental reslices.
 *
 * Usage: node wasm/tests/perf/incremental-reslicing-bench.mjs [--model PATH] [--out result.json]
 *   ORCA_ENGINE_MODULE selects the retained-Print build.
 *   BASELINE_ENGINE_MODULE selects the fresh-Print baseline build (optional).
 *   BENCH_THREADS sets the slicing threads (default: 4).
 */

import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { performance } from 'node:perf_hooks';
import { createEngineCore } from '../../web/engine-core.js';
import { hashGcode } from '../lib/gcode_hash.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '../../..');

const argv = process.argv.slice(2);
const arg = (name, def) => {
  const i = argv.indexOf(name);
  return i >= 0 ? argv[i + 1] : def;
};

const modelPath = path.resolve(arg('--model', path.join(repoRoot, 'wasm/build/models/3DBenchy.stl')));
const outFile = arg('--out', null);
const threads = Number(process.env.BENCH_THREADS || 4);

const currentModulePath = path.resolve(
  process.env.ORCA_ENGINE_MODULE ||
    path.join(repoRoot, 'wasm/build/orca-v250-wasm64/wasm/engine/orca_engine.mjs')
);
const baselineModulePath = process.env.BASELINE_ENGINE_MODULE
  ? path.resolve(process.env.BASELINE_ENGINE_MODULE)
  : null;

const bundleDir = path.join(repoRoot, 'wasm/build/tests-node');
const PRESETS = {
  printer: 'Voron 2.4 300 0.4 nozzle',
  process: '0.20mm Standard @Voron',
  filaments: ['Generic PLA @System']
};

function ensureAssets() {
  const needed = ['resources.json', 'profiles/Voron.json', 'profiles/OrcaFilamentLibrary.json'];
  if (needed.some((p) => !fs.existsSync(path.join(bundleDir, p)))) {
    execFileSync(
      process.execPath,
      [path.join(repoRoot, 'wasm/web/tools/pack_profiles.mjs'), repoRoot, bundleDir, 'Voron', 'OrcaFilamentLibrary'],
      { stdio: 'inherit' }
    );
  }
  if (!fs.existsSync(modelPath) && modelPath.endsWith('3DBenchy.stl')) {
    execFileSync('bash', [path.join(repoRoot, 'wasm/tests/data/fetch_models.sh')], { stdio: 'inherit' });
  }
}

function rawGcodeHash(buf) {
  const normalized = Buffer.from(buf).toString('utf8').replace(/^; generated by .*$/gm, '');
  return crypto.createHash('sha256').update(normalized).digest('hex');
}

async function createInstrumentedCore(modPath) {
  const mod = await import(modPath);
  const baseFactory = mod.createOrcaEngine || mod.default;
  let capturedModule = null;
  const wrappedFactory = async (overrides) => {
    capturedModule = await baseFactory(overrides);
    return capturedModule;
  };
  const core = await createEngineCore({ moduleFactory: wrappedFactory, threads });
  for (const f of ['resources.json', 'profiles/OrcaFilamentLibrary.json', 'profiles/Voron.json']) {
    await core.addVendorBundle(JSON.parse(fs.readFileSync(path.join(bundleDir, f), 'utf8')));
  }
  await core.call('init', { resourcesDir: '/resources', dataDir: '/data' });
  await core.call('loadVendors', {});
  await core.call('selectPresets', PRESETS);
  return {
    core,
    getHeapBytes: () => capturedModule?.HEAPU8?.byteLength ?? null
  };
}

async function main() {
  ensureAssets();
  const modelBytes = fs.readFileSync(modelPath);
  const modelName = path.basename(modelPath);

  const retained = await createInstrumentedCore(currentModulePath);
  const useSeparateBaseline = Boolean(baselineModulePath);
  const baseline = useSeparateBaseline ? await createInstrumentedCore(baselineModulePath) : retained;

  try {
    await retained.core.loadModel(modelName, modelBytes);
    await retained.core.call('arrange', {});
    const initialObjs = await retained.core.call('listObjects', {});
    const baseOffset = initialObjs[0].instances[0].offset;

    const accumulatedOptions = {};
    let currentOffset = [...baseOffset];

    const scenarios = [
      {
        name: 'initialSlice',
        outPath: '/out/bench_inc_1.gcode',
        apply: async () => {}
      },
      {
        name: 'repeatSamePath',
        outPath: '/out/bench_inc_1.gcode',
        apply: async () => {}
      },
      {
        name: 'repeatNewPath',
        outPath: '/out/bench_inc_2.gcode',
        apply: async () => {}
      },
      {
        name: 'gcodeSettingChange',
        outPath: '/out/bench_inc_3.gcode',
        apply: async (c) => {
          accumulatedOptions.fan_max_speed = '85';
          await c.call('setOptions', { options: { fan_max_speed: '85' } });
        }
      },
      {
        name: 'skirtSettingChange',
        outPath: '/out/bench_inc_4.gcode',
        apply: async (c) => {
          accumulatedOptions.skirt_loops = '2';
          await c.call('setOptions', { options: { skirt_loops: '2' } });
        }
      },
      {
        name: 'infillDensityChange',
        outPath: '/out/bench_inc_5.gcode',
        apply: async (c) => {
          accumulatedOptions.sparse_infill_density = '20%';
          await c.call('setOptions', { options: { sparse_infill_density: '20%' } });
        }
      },
      {
        name: 'moveObject',
        outPath: '/out/bench_inc_6.gcode',
        apply: async (c) => {
          currentOffset = [baseOffset[0] + 5, baseOffset[1] + 5, baseOffset[2]];
          const objs = await c.call('listObjects', {});
          await c.call('setInstanceTransform', {
            objectId: objs[0].id,
            instanceId: objs[0].instances[0].id,
            offset: currentOffset
          });
        }
      },
      {
        name: 'layerHeightChange',
        outPath: '/out/bench_inc_7.gcode',
        apply: async (c) => {
          accumulatedOptions.layer_height = '0.24';
          await c.call('setOptions', { options: { layer_height: '0.24' } });
        }
      }
    ];

    const results = {};

    // Run retained Print scenarios first so retained state is never reset by baseline runs
    for (const sc of scenarios) {
      await sc.apply(retained.core);
      const t0 = performance.now();
      const res = await retained.core.slice({ outPath: sc.outPath, threads });
      const retainedMs = performance.now() - t0;
      results[sc.name] = {
        retainedMs: +retainedMs.toFixed(1),
        retainedNormHash: hashGcode(Buffer.from(res.gcode)),
        retainedRawHash: rawGcodeHash(res.gcode),
        layers: res.layers,
        gcodeBytes: res.gcodeBytes,
        optionsSnapshot: { ...accumulatedOptions },
        offsetSnapshot: [...currentOffset]
      };
    }

    // Memory check across 10 consecutive incremental reslices (15% <-> 20%)
    const rssBefore = process.memoryUsage().rss;
    const heapBefore = retained.getHeapBytes();
    const memResliceMs = [];
    for (let i = 0; i < 10; i++) {
      const density = i % 2 === 0 ? '15%' : '20%';
      await retained.core.call('setOptions', { options: { sparse_infill_density: density } });
      const t0 = performance.now();
      await retained.core.slice({ outPath: '/out/bench_mem.gcode', threads });
      memResliceMs.push(+(performance.now() - t0).toFixed(1));
    }
    const rssAfter = process.memoryUsage().rss;
    const heapAfter = retained.getHeapBytes();

    // Run fresh Print baseline for every scenario and verify G-code hash equivalence
    for (const sc of scenarios) {
      const entry = results[sc.name];
      await baseline.core.call('resetOptions', {});
      await baseline.core.call('selectPresets', PRESETS);
      await baseline.core.loadModel(modelName, modelBytes);
      await baseline.core.call('arrange', {});
      if (Object.keys(entry.optionsSnapshot).length > 0) {
        await baseline.core.call('setOptions', { options: entry.optionsSnapshot });
      }
      const objs = await baseline.core.call('listObjects', {});
      await baseline.core.call('setInstanceTransform', {
        objectId: objs[0].id,
        instanceId: objs[0].instances[0].id,
        offset: entry.offsetSnapshot
      });

      const t0 = performance.now();
      const baseRes = await baseline.core.slice({ outPath: '/out/bench_base.gcode', threads });
      const baselineMs = performance.now() - t0;

      const baseNormHash = hashGcode(Buffer.from(baseRes.gcode));
      const baseRawHash = rawGcodeHash(baseRes.gcode);

      assert.equal(entry.retainedNormHash, baseNormHash, `${sc.name}: normalized G-code hash mismatch`);
      assert.equal(entry.retainedRawHash, baseRawHash, `${sc.name}: raw timestamp-stripped G-code hash mismatch`);

      entry.baselineMs = +baselineMs.toFixed(1);
      entry.speedup = +(baselineMs / Math.max(entry.retainedMs, 0.01)).toFixed(2);
      entry.hashMatch = true;
      delete entry.optionsSnapshot;
      delete entry.offsetSnapshot;
    }

    const report = {
      currentModule: currentModulePath,
      baselineModule: useSeparateBaseline ? baselineModulePath : 'fresh-loadModel-fallback',
      model: modelPath,
      threads,
      scenarios: results,
      memoryCheck10Reslices: {
        rssBeforeBytes: rssBefore,
        rssAfterBytes: rssAfter,
        rssDeltaBytes: rssAfter - rssBefore,
        heapBeforeBytes: heapBefore,
        heapAfterBytes: heapAfter,
        heapDeltaBytes: heapBefore !== null && heapAfter !== null ? heapAfter - heapBefore : null,
        resliceMs: memResliceMs
      }
    };

    console.log(JSON.stringify(report, null, 2));
    if (outFile) {
      fs.writeFileSync(outFile, JSON.stringify(report, null, 2));
    }
  } finally {
    retained.core.dispose();
    if (useSeparateBaseline) {
      baseline.core.dispose();
    }
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
