#!/usr/bin/env node
/**
 * Engine timing harness: times the engine operations the web app runs most
 * (preset changes, config reads, model import, project save/open for undo and
 * autosave, slicing) and records output hashes so a speed change can be
 * checked for identical results.
 *
 * Usage: node wasm/tests/perf/engine-bench.mjs [--runs N] [--model PATH] [--out result.json]
 *   ORCA_ENGINE_MODULE selects the engine (default: the STEP runtime build).
 *   BENCH_SKIP_SLICE=1 skips slicing, BENCH_THREADS sets the slicing threads.
 */

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { performance } from 'node:perf_hooks';
import { createEngineCore } from '../../web/engine-core.js';
import { hashGcode } from '../lib/gcode_hash.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '../../..');

const argv = process.argv.slice(2);
const arg = (name, def) => {
  const i = argv.indexOf(name);
  return i >= 0 ? argv[i + 1] : def;
};
const runs = Number(arg('--runs', '3'));
const modelArg = arg('--model', path.join(repoRoot, 'wasm/build/models/3DBenchy.stl'));
const outFile = arg('--out', null);
const threads = Number(process.env.BENCH_THREADS || 4);

const modulePath = path.resolve(process.env.ORCA_ENGINE_MODULE ||
  path.join(repoRoot, 'wasm/build/orca-step-runtime/wasm/engine/orca_engine.mjs'));
const bundleDir = path.join(repoRoot, 'wasm/build/tests-node');

function ensureBundles() {
  const needed = ['resources.json', 'profiles/Voron.json', 'profiles/OrcaFilamentLibrary.json'];
  if (needed.some((p) => !fs.existsSync(path.join(bundleDir, p)))) {
    execFileSync(process.execPath, [path.join(repoRoot, 'wasm/web/tools/pack_profiles.mjs'), repoRoot, bundleDir,
      'Voron', 'OrcaFilamentLibrary', 'BBL', 'Prusa'], { stdio: 'inherit' });
  }
}

const timings = {};
async function timed(name, fn) {
  const t0 = performance.now();
  const r = await fn();
  (timings[name] ||= []).push(performance.now() - t0);
  return r;
}
const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');
// G-code identity, ignoring the generation timestamp only.
const rawGcodeHash = (buf) => sha(Buffer.from(buf).toString('utf8').replace(/^; generated by .*$/m, ''));

async function main() {
  ensureBundles();
  const mod = await import(modulePath);
  const core = await timed('createEngine', () => createEngineCore({ moduleFactory: mod.createOrcaEngine || mod.default, threads }));
  for (const f of ['resources.json', 'profiles/OrcaFilamentLibrary.json', 'profiles/Voron.json']) {
    await core.addVendorBundle(JSON.parse(fs.readFileSync(path.join(bundleDir, f), 'utf8')));
  }
  await timed('init', () => core.call('init', { resourcesDir: '/resources', dataDir: '/data' }));
  await timed('loadVendors', () => core.call('loadVendors', {}));

  const presets = { printer: 'Voron 2.4 300 0.4 nozzle', process: '0.20mm Standard @Voron', filaments: ['Generic PLA @System'] };
  const results = { hashes: {} };
  for (let i = 0; i < runs; i++) await timed('selectPresets', () => core.call('selectPresets', presets));
  for (let i = 0; i < runs; i++) await timed('getConfig', () => core.call('getConfig', {}));
  for (let i = 0; i < runs; i++) await timed('getConfigDef', () => core.call('getConfigDef', {}));
  for (let i = 0; i < runs * 5; i++) {
    await timed('setOptions', () => core.call('setOptions', { options: { sparse_infill_density: i % 2 ? '20%' : '15%' } }));
  }
  await core.call('setOptions', { options: { sparse_infill_density: '15%' } });
  for (let i = 0; i < runs * 10; i++) await timed('listPresets', () => core.call('listPresets', { kind: 'filament' }));

  const modelBytes = fs.readFileSync(modelArg);
  const modelName = path.basename(modelArg);
  for (let i = 0; i < runs; i++) await timed('loadModel', () => core.loadModel(modelName, modelBytes));
  await timed('arrange', () => core.call('arrange', {}));
  let objects;
  for (let i = 0; i < runs * 10; i++) objects = await timed('listObjects', () => core.call('listObjects', {}));
  const objectId = (objects.objects || objects)[0].id;
  for (let i = 0; i < runs; i++) await timed('getMesh', () => core.call('getMesh', { objectId }));

  let projectBytes;
  for (let i = 0; i < runs; i++) {
    await timed('saveProject', () => core.call('saveProject', { path: '/out/bench.3mf' }));
    projectBytes = core.readFile('/out/bench.3mf');
  }
  results.projectSize = projectBytes.length;
  const projectCopy = '/tmp/engine-bench-project.3mf';
  fs.writeFileSync(projectCopy, projectBytes);
  results.projectPath = projectCopy;

  let gcodeFromLoad;
  if (!process.env.BENCH_SKIP_SLICE) {
    for (let i = 0; i < runs; i++) {
      const r = await timed('slice', () => core.slice({ outPath: '/out/bench.gcode' }));
      gcodeFromLoad = r.gcode;
      results.hashes[`slice${i}`] = hashGcode(Buffer.from(r.gcode));
      results.hashes[`sliceRaw${i}`] = rawGcodeHash(r.gcode);
    }
  }
  for (let i = 0; i < runs; i++) {
    core.writeFile('/models/bench-open.3mf', projectBytes);
    await timed('openProject', () => core.call('openProject', { path: '/models/bench-open.3mf' }));
  }
  if (!process.env.BENCH_SKIP_SLICE) {
    const r = await timed('sliceAfterOpen', () => core.slice({ outPath: '/out/bench2.gcode' }));
    results.hashes.sliceAfterOpen = hashGcode(Buffer.from(r.gcode));
    results.hashes.sliceAfterOpenRaw = rawGcodeHash(r.gcode);
    results.gcodeBytes = gcodeFromLoad.length;
    fs.writeFileSync('/tmp/engine-bench.gcode', gcodeFromLoad);
  }

  core.dispose();
  const summary = {};
  for (const [k, v] of Object.entries(timings)) {
    const s = [...v].sort((a, b) => a - b);
    summary[k] = { n: v.length, min: +s[0].toFixed(1), median: +s[Math.floor(s.length / 2)].toFixed(1), max: +s[s.length - 1].toFixed(1) };
  }
  const out = { module: modulePath, model: modelArg, threads, runs, summary, ...results };
  console.log(JSON.stringify(out, null, 2));
  if (outFile) fs.writeFileSync(outFile, JSON.stringify(out, null, 2));
  process.exit(0);
}

main().catch((e) => { console.error(e); process.exit(1); });
